#!/usr/bin/env node
/**
 * gen-defects-evidence.mjs — CLEAN-004 / R3-01 定点返工：DEFECTS §2「判别证据链」表的**机读抽取生成器**
 *
 * 目的（消除跨运行取值手工漂移）：
 *   `DEFECTS.md` §2 的判别证据链 (a)(c)(d) 三行曾填上一轮（R1 返工运行）的取值并自述「取自
 *   `report.json`（记录运行）」（R3 复审 `R3-01`，P2 阻断）。本脚本把该表**逐格**从
 *   `docs/evidence/CLEAN-004/report.json`（权威记录运行）直接抽取生成，使「文档 ⇄ 原件」逐字可对账。
 *
 * 用法（**只读**，不发起任何探针运行）：
 *   node docs\evidence\CLEAN-004\gen-defects-evidence.mjs                        # 打印表体（markdown，含 c)
 *   node docs\evidence\CLEAN-004\gen-defects-evidence.mjs --print                # 同上
 *   node docs\evidence\CLEAN-004\gen-defects-evidence.mjs --check                # 对账 DEFECTS.md 标记块
 *                                                                                # 一致 => exit 0；漂移 => exit 3
 *   node docs\evidence\CLEAN-004\gen-defects-evidence.mjs --write                # 仅重写标记块内内容
 *   node docs\evidence\CLEAN-004\gen-defects-evidence.mjs --report <path> --defects <path>
 *
 * 读取的原件字段（全部来自 `report.json`，无任何推断值）：
 *   `facts.overviewProbe.bindings.zz-first-probe` / `facts.overviewProbe.status`
 *   `facts.isolatedDisk.settingsYaml` / `.boundId` / `.boundIdOnDisk`
 *   `facts.isolatedDisk.sessionDirs` / `.sessionStore[<ws dir>]`
 *   `facts.isolatedDisk.hostWorkspaceJson` → `tables.workspaces[<wsId>].sessionIds|createdAt|updatedAt`
 *   `facts.sessionAckIds.hostWorkspaceSessionIds`
 *
 * 不变量：本脚本**不**读写探针（`probe-clean-004.mjs`）与 `falsifiability-check.mjs`，不发起运行。
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const BEGIN = '<!-- BEGIN: DEFECTS-EVIDENCE-CHAIN (generated by gen-defects-evidence.mjs) -->';
const END = '<!-- END: DEFECTS-EVIDENCE-CHAIN -->';
const BOUND_ID_KEY = 'zz-first-probe'; // fixture 中被自动链绑定的卡（与探针 fixture 一致）

function arg(name, dflt) {
  const i = process.argv.indexOf(name);
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : dflt;
}
const REPORT = path.resolve(arg('--report', path.join(HERE, 'report.json')));
const DEFECTS = path.resolve(arg('--defects', path.join(HERE, 'DEFECTS.md')));
const MODE = process.argv.includes('--check') ? 'check'
  : process.argv.includes('--write') ? 'write' : 'print';

const load = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));
const ids = (a) => JSON.stringify(a ?? []).replace(/"/g, '"');
const uniq = (a) => [...new Set(a ?? [])];
const fmt = (v, n = 8) => (v == null ? null : String(v).slice(0, n) + '…');

/** 表体（不含表头/分隔行，含 (a)~(d) 与 (e) 说明行）—— 表头/列数：`| # | 观测面 | 实测值（权威记录运行） | 推论 |` */
export function buildRows(report) {
  const facts = report.facts ?? {};
  const ov = facts.overviewProbe ?? {};
  const disk = facts.isolatedDisk ?? {};
  const bindings = ov.bindings ?? {};
  const boundId = bindings[BOUND_ID_KEY] ?? disk.boundId;

  // (c) 会话存储目录 = 由隔离 novels 根派生（与探针落盘口径一致）
  const wsDir = (disk.sessionDirs ?? []).find((d) => typeof d === 'string') ?? null;
  const storeIds = wsDir ? (disk.sessionStore ?? {})[wsDir] : undefined;

  // (d) 宿主工作区表
  let wsJson = null;
  try { wsJson = JSON.parse(disk.hostWorkspaceJson ?? 'null'); } catch { wsJson = null; }
  const tables = wsJson?.tables?.workspaces ?? {};
  const wsId = Object.keys(tables)[0] ?? null;
  const ws = wsId ? tables[wsId] : null;

  const ackIds = facts.sessionAckIds ?? {};
  const rows = [];

  // (a) 插件 overview API
  rows.push(`| a | 插件 overview API（\`GET /api/overview\`） | \`bindings.${BOUND_ID_KEY} = ${boundId}\`（HTTP ${ov.status ?? 'n/a'}） | 自动链**已写入绑定** |`);
  // (b) 隔离实例 settings.yaml
  const yamlHas = typeof disk.settingsYaml === 'string' && disk.settingsYaml.includes(boundId);
  rows.push(`| b | 隔离实例 \`settings.yaml\` | \`novel-writing.bindings.${BOUND_ID_KEY} = ${disk.boundId ?? 'n/a'}\`、\`boundIdOnDisk = ${disk.boundIdOnDisk}\`（\`facts.isolatedDisk.settingsYaml\` 含该 id = ${yamlHas}） | 持久化面成功 |`);
  // (c) 隔离实例会话存储
  const uniqStore = uniq(storeIds);
  rows.push(`| c | 隔离实例会话存储 \`$DSH_HOME/sessions/<ws-dir>/\`（` + '`<ws-dir> = --…-novels--`，全名见 `report.json.facts.isolatedDisk.sessionDirs[0]`）' + ` | ${ids(storeIds)}（去重后 ${ids(uniqStore)}，共 ${(storeIds ?? []).length} 项；\`boundIdOnDisk = ${disk.boundIdOnDisk}\`） | 会话**确实建出来了**（与宿主默认会话同目录同级） |`);
  // (d) 宿主工作区表
  const wsIds = ws?.sessionIds ?? [];
  rows.push(
    `| d | 宿主工作区表 \`$DSH_HOME/storages/workspace.json\` | \`tables.workspaces["${wsId ?? 'n/a'}"].sessionIds\` **首项即该会话**（${ids(uniq(wsIds))}），` +
    `\`updatedAt = ${ws?.updatedAt ?? 'n/a'}\`、\`createdAt = ${ws?.createdAt ?? 'n/a'}\`——**取值口径**：本行全部数值由 \`report.json\`（权威记录运行）经 ` +
    '`gen-defects-evidence.mjs` **逐格机读抽取**（无手工转录）；`workspace.createdAt` 是宿主工作区表条目的创建时刻（≠ 会话创建时刻），两者相差 ' +
    `${ws ? Math.round((Date.parse(ws.updatedAt) - Date.parse(ws.createdAt)) / 1000) : 'n/a'} s；独立复跑 \`report-run1.json\` 自洽给出另一组（\`workspaces["5a763818-…"]\`，\`session-52f36262-…\`，\`updatedAt = 04:06:02.503Z\`）⇒ 跨运行**不得混引** | **宿主自己把该会话挂进了 fixture 工作区** |`);
  // (a') 宿主三面（本轮新增，闭合 (c)/(d) 的“另一条 id”来源）
  const hostIds = ackIds.hostWorkspaceSessionIds ?? [];
  rows.push(`| a′ | 插件宿主面 \`overview.bindings\` + \`storages/workspace.json\` + \`sessions/<ws>/\` | \`facts.sessionAckIds.hostWorkspaceSessionIds = ${ids(hostIds)}\`（\`boundId = ${ackIds.boundId}\`；\`source = ${ackIds.source}\`） | (a)(c)/(d) 中**另一条** id \`${fmt(hostIds[1] ?? hostIds[0], 26)}\` 是宿主默认会话，非本场景产物 |`);

  return rows.join('\n');
}

function section() {
  const src = fs.readFileSync(DEFECTS, 'utf8');
  const i = src.indexOf(BEGIN);
  const j = src.indexOf(END);
  if (i < 0 || j < 0 || j < i) return null;
  return { src, i, j, body: src.slice(i + BEGIN.length, j).replace(/^\n+/, '').replace(/\n+$/, '') };
}

const report = load(REPORT);
const generated = buildRows(report);
const stamp = `_generated from \`report.json\` tally=${JSON.stringify(report.tally)} head=${String(report.head ?? '').slice(0, 7)} at ${new Date().toISOString()}_`;

if (MODE === 'print') {
  console.log(generated);
  console.log(stamp);
  process.exit(0);
}

const sec = section();
if (!sec) {
  console.error(`CHECK-FAILED: markers not found in ${DEFECTS} (${BEGIN} / ${END})`);
  process.exit(3);
}
if (MODE === 'check') {
  // R4 NEW-R4-02 订正：先归一行尾（CRLF/LF）再对账——否则文档化的自校验恒红，
  // 且 --write 会在 CRLF 文档里写入 LF 行造成混合 EOL。内容比较不受影响。
  const norm = (s) => s.replace(/\r\n/g, '\n').replace(/\r/g, '\n');
  const same = norm(sec.body).trim() === norm(generated).trim();
  console.log(`DEFECTS-EVIDENCE-CHAIN ${same ? 'IN-SYNC' : 'DRIFT'} (EOL-normalized)`);
  if (!same) {
    console.error('--- document body ---');
    console.error(sec.body);
    console.error('--- generated body ---');
    console.error(generated);
    process.exit(3);
  }
  console.log(`rows=${generated.split('\n').length} bytes=${generated.length}`);
  process.exit(0);
}
const out = sec.src.slice(0, sec.i + BEGIN.length) + '\n' + generated + '\n' + sec.src.slice(sec.j);
fs.writeFileSync(DEFECTS, out, 'utf8');
console.log(`WROTE ${DEFECTS} rows=${generated.split('\n').length}`);
process.exit(0);
